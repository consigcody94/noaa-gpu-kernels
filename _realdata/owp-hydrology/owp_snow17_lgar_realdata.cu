static void die(const char* msg) { fprintf(stderr, "FATAL: %s\n", msg); exit(1); }

#define SNOW_DT_HOURS 24.0f   // daily timestep of the HHWM8 ex1 case study
#define LGAR_DT 3600.0f       // hourly forcing resolution per LASAM configs

// ---- Snow17: real HHWM8 params/forcing + CPU-reference state trajectory ----
typedef struct {
    int nlib;
    Snow17State*   state;     // [nlib] state BEFORE the step
    Snow17Params*  params;    // [nlib]
    Snow17Forcing* forcing;   // [nlib]
} SnowLibrary;

static SnowLibrary g_snow;

void load_snow_library(const char* path) {
    FILE* f = fopen(path, "rb");
    if (!f) die("cannot open snow17_realdata.bin (run prep_snow17.py)");
    int magic, nhru, nrec;
    if (fread(&magic, 4, 1, f) != 1 || magic != 0x534E4F57) die("snow magic");
    fread(&nhru, 4, 1, f);
    fread(&nrec, 4, 1, f);

    Snow17Params* ps = (Snow17Params*)malloc(nhru * sizeof(Snow17Params));
    for (int h = 0; h < nhru; h++) {
        float v[10];
        fread(v, 4, 10, f);
        ps[h].scf = v[0]; ps[h].mfmax = v[1]; ps[h].mfmin = v[2]; ps[h].uadj = v[3];
        ps[h].si = v[4]; ps[h].tipm = v[5]; ps[h].mbase = v[6]; ps[h].plwhc = v[7];
        ps[h].daygm = v[8]; ps[h].pxtemp = v[9];
    }
    float* forc = (float*)malloc((size_t)nhru * nrec * 2 * 4);
    fread(forc, 4, (size_t)nhru * nrec * 2, f);
    fclose(f);

    g_snow.nlib = nhru * nrec;
    g_snow.state = (Snow17State*)malloc((size_t)g_snow.nlib * sizeof(Snow17State));
    g_snow.params = (Snow17Params*)malloc((size_t)g_snow.nlib * sizeof(Snow17Params));
    g_snow.forcing = (Snow17Forcing*)malloc((size_t)g_snow.nlib * sizeof(Snow17Forcing));

    // sequential drive with the untouched CPU reference (cold start per HRU)
    for (int h = 0; h < nhru; h++) {
        Snow17State st;
        memset(&st, 0, sizeof(st));
        for (int t = 0; t < nrec; t++) {
            int idx = h * nrec + t;
            Snow17Forcing fz;
            fz.ta = forc[((size_t)h * nrec + t) * 2 + 0];
            fz.px = forc[((size_t)h * nrec + t) * 2 + 1];
            g_snow.state[idx] = st;          // pre-step state
            g_snow.params[idx] = ps[h];
            g_snow.forcing[idx] = fz;
            float runoff;
            cpu_snow17(&st, &ps[h], &fz, &runoff, SNOW_DT_HOURS, 1);
        }
    }
    printf("[data] Snow17 library: %d real (state,forcing) tuples (%d HRUs x %d days, "
           "HHWM8 1970-2015)\n", g_snow.nlib, nhru, nrec);
    free(ps); free(forc);
}

void fill_snow_batch(Snow17State* st, Snow17Params* p, Snow17Forcing* fz, int nc) {
    for (int c = 0; c < nc; c++) {
        int s = c % g_snow.nlib;
        st[c] = g_snow.state[s];
        p[c] = g_snow.params[s];
        fz[c] = g_snow.forcing[s];
    }
}

// ---- LGAR: real site params/forcing + CPU-reference cumulative-infiltration ----
typedef struct {
    int nlib;
    LGARParams* params;   // [nlib]
    float* precip;        // [nlib] m/s
    float* cum0;          // [nlib] pre-step cumulative infiltration (m)
} LgarLibrary;

static LgarLibrary g_lgar;

void load_lgar_library(const char* path) {
    FILE* f = fopen(path, "rb");
    if (!f) die("cannot open lgar_realdata.bin (run prep_lgar.py)");
    int magic, nsite;
    if (fread(&magic, 4, 1, f) != 1 || magic != 0x4C474152) die("lgar magic");
    fread(&nsite, 4, 1, f);

    // first pass: read everything
    LGARParams* sp = (LGARParams*)malloc(nsite * sizeof(LGARParams));
    float** series = (float**)malloc(nsite * sizeof(float*));
    int* nrec = (int*)malloc(nsite * sizeof(int));
    int total = 0;
    for (int s = 0; s < nsite; s++) {
        float v[5];
        fread(v, 4, 5, f);
        sp[s].Ks = v[0]; sp[s].porosity = v[1]; sp[s].wetting_front_suction = v[2];
        sp[s].initial_moisture = v[3]; sp[s].soil_depth = v[4];
        fread(&nrec[s], 4, 1, f);
        series[s] = (float*)malloc((size_t)nrec[s] * 4);
        fread(series[s], 4, nrec[s], f);
        total += nrec[s];
    }
    fclose(f);

    g_lgar.nlib = total;
    g_lgar.params = (LGARParams*)malloc((size_t)total * sizeof(LGARParams));
    g_lgar.precip = (float*)malloc((size_t)total * 4);
    g_lgar.cum0 = (float*)malloc((size_t)total * 4);

    int idx = 0;
    for (int s = 0; s < nsite; s++) {
        float F = 0.0f;   // cold start
        for (int t = 0; t < nrec[s]; t++) {
            g_lgar.params[idx] = sp[s];
            g_lgar.precip[idx] = series[s][t];
            g_lgar.cum0[idx] = F;             // pre-step state
            float fi, ro;
            cpu_lgar(&sp[s], &series[s][t], &fi, &ro, &F, LGAR_DT, 1);
            idx++;
        }
        free(series[s]);
    }
    printf("[data] LGAR library: %d real (state,forcing) tuples (%d sites x 8760 h, "
           "Phillipsburg WY2017 + Bushland WY2021)\n", g_lgar.nlib, nsite);
    free(sp); free(series); free(nrec);
}

void fill_lgar_batch(LGARParams* p, float* precip, float* cum, int nc) {
    for (int c = 0; c < nc; c++) {
        int s = c % g_lgar.nlib;
        p[c] = g_lgar.params[s];
        precip[c] = g_lgar.precip[s];
        cum[c] = g_lgar.cum0[s];
    }
}

