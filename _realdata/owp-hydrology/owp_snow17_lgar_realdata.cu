void bench_snow17(int ncatch) {
    printf("--- Snow17 (REAL HHWM8 data): %d catchments ---\n", ncatch);

    Snow17State *hs=(Snow17State*)malloc((size_t)ncatch*sizeof(Snow17State));
    Snow17State *hs_gpu=(Snow17State*)malloc((size_t)ncatch*sizeof(Snow17State));
    Snow17Params *hp=(Snow17Params*)malloc((size_t)ncatch*sizeof(Snow17Params));
    Snow17Forcing *hf=(Snow17Forcing*)malloc((size_t)ncatch*sizeof(Snow17Forcing));
    float *hr_cpu=(float*)malloc((size_t)ncatch*4), *hr_gpu=(float*)malloc((size_t)ncatch*4);

    fill_snow_batch(hs, hp, hf, ncatch);   // REAL DATA (was gen_snow_data)
    memcpy(hs_gpu, hs, (size_t)ncatch*sizeof(Snow17State));

    clock_t t0=clock();
    cpu_snow17(hs, hp, hf, hr_cpu, SNOW_DT_HOURS, ncatch);
    double cpu_ms=1000.0*(clock()-t0)/(double)CLOCKS_PER_SEC;

    Snow17State *ds; Snow17Params *dp; Snow17Forcing *df; float *dr;
    cudaMalloc(&ds, (size_t)ncatch*sizeof(Snow17State));
    cudaMalloc(&dp, (size_t)ncatch*sizeof(Snow17Params));
    cudaMalloc(&df, (size_t)ncatch*sizeof(Snow17Forcing));
    cudaMalloc(&dr, (size_t)ncatch*4);
    cudaMemcpy(dp, hp, (size_t)ncatch*sizeof(Snow17Params), cudaMemcpyHostToDevice);
    cudaMemcpy(df, hf, (size_t)ncatch*sizeof(Snow17Forcing), cudaMemcpyHostToDevice);

    int thr=256, blk=(ncatch+thr-1)/thr;

    // Warmup
    cudaMemcpy(ds, hs_gpu, (size_t)ncatch*sizeof(Snow17State), cudaMemcpyHostToDevice);
    kernel_snow17<<<blk,thr>>>(ds, dp, df, dr, SNOW_DT_HOURS, ncatch);
    cudaDeviceSynchronize();

    cudaEvent_t e0,e1; cudaEventCreate(&e0); cudaEventCreate(&e1);
    int runs=50;
    cudaEventRecord(e0);
    for(int r=0;r<runs;r++){
        cudaMemcpy(ds, hs_gpu, (size_t)ncatch*sizeof(Snow17State), cudaMemcpyHostToDevice);
        kernel_snow17<<<blk,thr>>>(ds, dp, df, dr, SNOW_DT_HOURS, ncatch);
    }
    cudaEventRecord(e1); cudaEventSynchronize(e1);
    float gpu_ms; cudaEventElapsedTime(&gpu_ms,e0,e1); gpu_ms/=runs;

    // Get results with fresh state
    cudaMemcpy(ds, hs_gpu, (size_t)ncatch*sizeof(Snow17State), cudaMemcpyHostToDevice);
    kernel_snow17<<<blk,thr>>>(ds, dp, df, dr, SNOW_DT_HOURS, ncatch);
    cudaMemcpy(hr_gpu, dr, (size_t)ncatch*4, cudaMemcpyDeviceToHost);

    float max_abs=0, max_rel=0; int nan_c=0, fail_c=0;
    for(int c=0;c<ncatch;c++){
        if(isnan(hr_gpu[c])){nan_c++;continue;}
        float ae=fabsf(hr_gpu[c]-hr_cpu[c]);
        if(ae>max_abs)max_abs=ae;
        if(fabsf(hr_cpu[c])>1e-10f){
            float re=ae/fabsf(hr_cpu[c]);
            if(re>max_rel)max_rel=re;
            if(re>1e-4f)fail_c++;
        }
    }

    printf("  CPU: %.1f ms | GPU: %.3f ms | Speedup: %.1fx\n", cpu_ms, gpu_ms, cpu_ms/gpu_ms);
    printf("  Max abs: %.2e | Max rel: %.2e | NaN: %d | >0.01%% err: %d/%d\n",
           max_abs, max_rel, nan_c, fail_c, ncatch);
    printf("  Status: %s\n\n",
           (nan_c==0&&max_rel<1e-4f)?"PASS":(nan_c==0&&max_rel<1e-2f)?"PASS (fast exp)":"NEEDS REVIEW");

    free(hs);free(hs_gpu);free(hp);free(hf);free(hr_cpu);free(hr_gpu);
    cudaFree(ds);cudaFree(dp);cudaFree(df);cudaFree(dr);
    cudaEventDestroy(e0);cudaEventDestroy(e1);
}

